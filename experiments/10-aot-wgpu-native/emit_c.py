#!/usr/bin/env python3
"""AOT front half of exp10: display-list JSON -> baked GPU data + WGSL.

Runs at BUILD time only. The generated scene_data.h contains:

  * kSceneOps[]        rect metadata (for reporting / generic op loop)
  * kSceneVertices[]   6 vertices per rect, clip-space pos (vec2) + color (unorm8x4)
  * kSceneShaderWGSL   the generated shader that consumes those vertices
  * SCENE_WIDTH/HEIGHT and the clear color (op[0])

The runtime has no JSON parser and no Python dependency: geometry and shader
are compiled into the executable.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HEX = set("0123456789abcdef")


def parse_color(value: object) -> tuple[int, int, int, int]:
    if not isinstance(value, str):
        raise ValueError(f"fill must be a string, got {type(value).__name__}")
    text = value.strip().lower()
    if not text.startswith("#"):
        raise ValueError(f"fill must start with '#': {value!r}")
    digits = text[1:]
    if len(digits) == 3:
        digits = "".join(ch * 2 for ch in digits)
    elif len(digits) == 6:
        digits += "ff"
    elif len(digits) != 8:
        raise ValueError(f"fill must be #rgb, #rrggbb or #rrggbbaa: {value!r}")
    if any(ch not in HEX for ch in digits):
        raise ValueError(f"fill has non-hex characters: {value!r}")
    r, g, b, a = (int(digits[i : i + 2], 16) for i in range(0, 8, 2))
    return r, g, b, a


def number(raw: object, field: str, index: int) -> float:
    if isinstance(raw, bool) or not isinstance(raw, (int, float)):
        raise ValueError(f"op[{index}].{field} must be a number, got {raw!r}")
    return float(raw)


def load_ir(path: Path) -> tuple[int, int, list[dict]]:
    with path.open("r", encoding="utf-8-sig") as handle:
        doc = json.load(handle)

    viewport = doc.get("viewport")
    if not isinstance(viewport, dict):
        raise ValueError("IR must contain a 'viewport' object")
    width = viewport.get("width")
    height = viewport.get("height")
    if not isinstance(width, int) or not isinstance(height, int) or width <= 0 or height <= 0:
        raise ValueError("viewport.width and viewport.height must be positive integers")

    ops = doc.get("ops")
    if not isinstance(ops, list) or not ops:
        raise ValueError("IR must contain a non-empty 'ops' array")

    rects: list[dict] = []
    for index, op in enumerate(ops):
        if not isinstance(op, dict):
            raise ValueError(f"op[{index}] must be an object")
        if op.get("type") != "rect":
            raise ValueError(f"op[{index}].type {op.get('type')!r} is not supported (rect only)")
        x = number(op.get("x"), "x", index)
        y = number(op.get("y"), "y", index)
        w = number(op.get("w"), "w", index)
        h = number(op.get("h"), "h", index)
        if w <= 0 or h <= 0:
            raise ValueError(f"op[{index}] must have positive w/h, got {w}x{h}")
        r, g, b, a = parse_color(op.get("fill"))
        rects.append(
            {
                "x": x,
                "y": y,
                "w": w,
                "h": h,
                "rgba": (r << 24) | (g << 16) | (b << 8) | a,
                "rgb": (r, g, b, a),
                "fill": op["fill"],
            }
        )
    return width, height, rects


def f32(value: float) -> str:
    text = f"{value:.7f}".rstrip("0")
    if text.endswith("."):
        text += "0"
    return f"{text}f"


def ndc(x: float, y: float, width: int, height: int) -> tuple[str, str]:
    return f32(x / width * 2.0 - 1.0), f32(1.0 - y / height * 2.0)


def vertex_line(x: float, y: float, rgb: tuple[int, int, int, int], w: int, h: int) -> str:
    nx, ny = ndc(x, y, w, h)
    r, g, b, a = rgb
    return f"    {{ {nx:>12}, {ny:>12}, {r:3d}, {g:3d}, {b:3d}, {a:3d} }},"


SHADER_LINES = [
    "// Generated by emit_c.py: display-list geometry consumer.",
    "// Vertex format: @location(0)=clip-space vec2, @location(1)=unorm8x4 color.",
    "struct VsOut {",
    "    @builtin(position) clip_pos: vec4f,",
    "    @location(0) color: vec4f,",
    "};",
    "",
    "@vertex",
    "fn vs_main(@location(0) pos: vec2f, @location(1) color: vec4f) -> VsOut {",
    "    var o: VsOut;",
    "    o.clip_pos = vec4f(pos, 0.0, 1.0);",
    "    o.color = color;",
    "    return o;",
    "}",
    "",
    "@fragment",
    "fn fs_main(in: VsOut) -> @location(0) vec4f {",
    "    return in.color;",
    "}",
]


def render_header(ir_path: Path, digest: str, width: int, height: int, rects: list[dict]) -> str:
    clear = rects[0]["rgb"]
    lines = [
        "/* AUTO-GENERATED by emit_c.py from display_list.json. DO NOT EDIT. */",
        f"/* source: {ir_path.name}  sha256: {digest} */",
        f"/* scene: {width}x{height}, {len(rects)} rect op(s), painter's order, 6 verts/op */",
        "#ifndef SCENE_DATA_H",
        "#define SCENE_DATA_H",
        "",
        "/* Keep this layout in sync with the vertex buffer layout in runtime_gpu.c. */",
        "typedef struct {",
        "    float x, y;                   /* clip space, -1..1 */",
        "    unsigned char r, g, b, a;     /* normalized unorm8x4 */",
        "} SceneVertex;",
        "",
        "typedef struct {",
        "    float x, y, w, h;             /* device px, top-left origin */",
        "    unsigned int rgba;            /* 0xRRGGBBAA */",
        "} RectOp;",
        "",
        f"#define SCENE_WIDTH  {width}",
        f"#define SCENE_HEIGHT {height}",
        f"#define SCENE_OP_COUNT {len(rects)}",
        f"#define SCENE_VERTEX_COUNT {len(rects) * 6}",
        "#define SCENE_VERTEX_STRIDE 12",
        f"#define SCENE_CLEAR_R ({clear[0]}.0f / 255.0f)",
        f"#define SCENE_CLEAR_G ({clear[1]}.0f / 255.0f)",
        f"#define SCENE_CLEAR_B ({clear[2]}.0f / 255.0f)",
        f"#define SCENE_CLEAR_A ({clear[3]}.0f / 255.0f)",
        "",
        "static const RectOp kSceneOps[SCENE_OP_COUNT] = {",
    ]
    for op in rects:
        lines.append(
            "    {{ {x:>7}, {y:>7}, {w:>7}, {h:>7}, 0x{rgba:08X}u }}, /* {fill} */".format(
                x=f32(op["x"]), y=f32(op["y"]), w=f32(op["w"]), h=f32(op["h"]),
                rgba=op["rgba"], fill=op["fill"],
            )
        )
    lines += [
        "};",
        "",
        "/* Two triangles per rect: TL, TR, BR, TL, BR, BL. */",
        "static const SceneVertex kSceneVertices[SCENE_VERTEX_COUNT] = {",
    ]
    for op in rects:
        x, y, w, h = op["x"], op["y"], op["w"], op["h"]
        rgb = op["rgb"]
        lines.append(f"    /* rect {op['fill']} at ({x:g},{y:g}) {w:g}x{h:g} */")
        for vx, vy in ((x, y), (x + w, y), (x + w, y + h), (x, y), (x + w, y + h), (x, y + h)):
            lines.append(vertex_line(vx, vy, rgb, width, height))
    lines.append("};")
    lines.append("")
    lines.append("static const char kSceneShaderWGSL[] =")
    for line in SHADER_LINES:
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{escaped}\\n"')
    lines.append("    ;")
    lines += [
        "",
        "#endif /* SCENE_DATA_H */",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Bake display-list JSON into GPU vertex data + WGSL")
    parser.add_argument("--ir", default="display_list.json", type=Path)
    parser.add_argument("--out", default="scene_data.h", type=Path)
    args = parser.parse_args()

    if not args.ir.exists():
        print(f"error: IR not found: {args.ir}", file=sys.stderr)
        return 1
    try:
        width, height, rects = load_ir(args.ir)
    except (ValueError, json.JSONDecodeError) as exc:
        print(f"error: invalid IR: {exc}", file=sys.stderr)
        return 1

    raw = args.ir.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()[:16]
    header = render_header(args.ir, digest, width, height, rects)
    args.out.write_text(header, encoding="utf-8", newline="\n")

    print(
        f"emit_c: {args.ir} -> {args.out} | {len(rects)} rect ops, "
        f"{len(rects) * 6} vertices, {width}x{height}, clear=#{rects[0]['fill'].lstrip('#')[:6]}, "
        f"sha256:{digest}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Generate the media-library pilot `ui.json` (webnative.ui-tree/2, hand-authored).

Layout (1280x800 default):
  header  : y=20..76
  scroll  : y=76..496, overflow: scroll, padding 16, content 1200x388
  grid    : repeat(auto-fill, 180px), gap 16, 18 image cards (180x240)
  footer  : y=504..544

At 1280 the grid has 6 columns (1200 content), at 800 it has 3 (720 content).
The posters are generated by make_posters.py; `src` is relative to this file.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
COUNT = 18
FITS = ("cover", "fill", "contain")


def style(**values) -> dict:
    base = {
        "display": "block",
        "direction": 1,
        "justify": 0,
        "align": 3,
        "wrap": 0,
        "width_px": -1.0,
        "height_px": -1.0,
        "width_pct": 0.0,
        "height_pct": 0.0,
        "margin": [0, 0, 0, 0],
        "padding": [0, 0, 0, 0],
        "gap": 0.0,
        "font_size": 16.0,
        "box_sizing": "border-box",
    }
    base.update(values)
    return base


def main() -> int:
    nodes: list[dict] = []

    def add(node: dict) -> int:
        index = len(nodes)
        node["id"] = index
        nodes.append(node)
        return index

    root = add({
        "id": 0, "parent": -1, "children": [], "kind": "block",
        "name": "body.root", "tag": "body",
        "style": style(display="block", width_px=-1.0, height_px=-1.0,
                       width_pct=100.0, height_pct=100.0,
                       background="#0b0e14"),
    })
    header = add({
        "parent": root, "children": [], "kind": "block",
        "name": "body.root/div.header", "tag": "div",
        "style": style(margin=[20, 24, 8, 24], height_px=56.0,
                       background="#121824"),
    })
    scroll = add({
        "parent": root, "children": [], "kind": "block",
        "name": "body.root/div.scroll", "tag": "div",
        "style": style(margin=[0, 24, 0, 24], height_px=420.0,
                       padding=[16, 16, 16, 16],
                       overflow="scroll", background="#10141b"),
    })
    footer = add({
        "parent": root, "children": [], "kind": "block",
        "name": "body.root/div.footer", "tag": "div",
        "style": style(margin=[8, 24, 0, 24], height_px=40.0,
                       background="#1a1f2a"),
    })
    grid = add({
        "parent": scroll, "children": [], "kind": "grid",
        "name": "body.root/div.scroll/div.grid", "tag": "div",
        "style": style(display="grid",
                       grid_template_columns={"mode": "auto_fill", "size_px": 180},
                       grid_auto_rows=240.0,
                       gap=16.0, row_gap=16.0, column_gap=16.0),
    })
    nodes[root]["children"] = [header, scroll, footer]
    nodes[scroll]["children"] = [grid]

    for i in range(COUNT):
        fit = FITS[i % len(FITS)]
        index = add({
            "parent": grid, "children": [], "kind": "image",
            "name": f"body.root/div.scroll/div.grid/img.poster[{i}]",
            "tag": "img",
            "style": style(width_px=180.0, height_px=240.0,
                           background="#1a1f2a"),
            "image": {
                "src": f"posters/poster-{i + 1:02d}.png",
                "alt": f"Poster {i + 1}",
                "object_fit": fit,
            },
        })
        nodes[grid]["children"].append(index)

    tree = {
        "schema": "webnative.ui-tree/2",
        "viewport": {"width": 1280, "height": 800},
        "source": {"html": "pilot-media-library/ui.json", "css": ""},
        "node_count": len(nodes),
        "rule_count": 0,
        "nodes": nodes,
    }
    out = HERE / "ui.json"
    out.write_text(json.dumps(tree, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(nodes)} nodes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

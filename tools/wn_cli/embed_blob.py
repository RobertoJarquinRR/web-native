#!/usr/bin/env python3
"""Embed a .wnui document as a C byte array.

The runtime's builtin page is parsed from an embedded blob (see
`wn_document_builtin`), so a build only needs this generated header next to the
C header that used to hold the ui_data tables. No linker step or extra dependency.

Usage:
  python tools/wn_cli/embed_blob.py --blob builtin.wnui --header builtin_blob.h
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

DEFAULT_SYMBOL = "kBuiltinBlob"
BYTES_PER_LINE = 12


def render(blob: bytes, source: str, symbol: str) -> str:
    size_symbol = f"{symbol}Size"
    lines = [
        "/* Generated by tools/wn_cli/embed_blob.py. Do not edit. */",
        f"/* source: {source} ({len(blob)} bytes) */",
        "#ifndef WN_BUILTIN_BLOB_H",
        "#define WN_BUILTIN_BLOB_H",
        "",
        f"static const unsigned char {symbol}[] = {{",
    ]
    for offset in range(0, len(blob), BYTES_PER_LINE):
        chunk = blob[offset:offset + BYTES_PER_LINE]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.append("};")
    lines.append(f"static const unsigned long {size_symbol} = {len(blob)}ul;")
    lines.append("")
    lines.append("#endif /* WN_BUILTIN_BLOB_H */")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--blob", required=True, help="input .wnui document")
    parser.add_argument("--header", required=True, help="output C header")
    parser.add_argument("--symbol", default=DEFAULT_SYMBOL,
                        help=f"array symbol (default {DEFAULT_SYMBOL})")
    args = parser.parse_args(argv)

    blob_path = Path(args.blob)
    if not blob_path.is_file():
        print(f"error: blob not found: {blob_path}", file=sys.stderr)
        return 1
    blob = blob_path.read_bytes()
    if not blob:
        print(f"error: empty blob: {blob_path}", file=sys.stderr)
        return 1

    header_path = Path(args.header)
    header_path.parent.mkdir(parents=True, exist_ok=True)
    text = render(blob, blob_path.name, args.symbol)
    header_path.write_text(text, encoding="utf-8", newline="\n")
    print(f"embed-blob: {len(blob)} bytes -> {header_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

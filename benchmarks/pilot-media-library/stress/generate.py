        '<html lang="es">\n'
        "<head>\n"
        '  <meta charset="utf-8">\n'
        f"  <title>webnative stress \u2014 {count} cards</title>\n"
        '  <link rel="stylesheet" href="style.css">\n'
        "</head>\n"
        '<body class="root">\n'
        '  <div class="sidebar">\n'
        '    <div class="brand">\n'
        '      <div class="brand-title">webnative</div>\n'
        f'      <div class="brand-sub">stress {count}</div>\n'
        "    </div>\n"
        '    <div class="nav-list">\n'
        f"{nav}"
        "    </div>\n"

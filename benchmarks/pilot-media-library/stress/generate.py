#!/usr/bin/env python3
"""Generate the R2 stress fixtures (cards + synthetic nested layout).

Everything is written under benchmarks/pilot-media-library/stress/variants/:

  variants/<id>/page/index.html
  variants/<id>/page/style.css
  variants/<id>/build/            (created later by run_stress.py)

Two families:

  cards-NNN   media grid, NNN cards. Posters are the 30 pilot posters cycled
              (no new assets). Grid contract:
                 repeat(auto-fill, 180px), gap 16px, vertical scroll
                 card 180x240 = poster 180x180 + meta 60
  nodes-NNN   synthetic nested layout with exactly NNN div nodes (no text, no
              images). The tree is root -> 12 frames -> board -> 8 columns ->
              8 rows -> cells. Depth to a cell: 17 levels.

The script is deterministic and idempotent. It also writes
variants/manifest.json with the expected geometry used by run_stress.py.

Usage:
    src\\frontend\\python\\.venv\\Scripts\\python.exe stress\\generate.py
"""

